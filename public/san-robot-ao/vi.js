(function() {
  // Mặc định dùng tiếng Việt nếu người dùng chưa chọn ngôn ngữ nào.
  try {
    if (!localStorage.getItem('LANG')) {
      localStorage.setItem('LANG', 'vi');
    }
  } catch (e) { /* trình duyệt chặn localStorage: vẫn chạy bằng tiếng Việt */ }
  LANG = (function() {
    try { return localStorage.getItem('LANG') || 'vi'; } catch (e) { return 'vi'; }
  })();

  function applyVi(keys) {
    for (let key of keys) {
      if (!(key in SRA_VI)) continue;
      if (typeof MSGS[key] == 'undefined') {
        MSGS[key] = {};
      }
      MSGS[key].vi = SRA_VI[key];
    }
    MSGS_KEYS = Object.keys(MSGS);
  }

  applyVi(Object.keys(SRA_VI));

  // robotTemplates.js và các sân gọi i18n.append(), thay nguyên mục,
  // nên gắn lại bản tiếng Việt sau mỗi lần append.
  const originalAppend = i18n.append;
  i18n.append = function(msgs) {
    originalAppend(msgs);
    applyVi(Object.keys(msgs));
  };

  // Cho phép mã của Sân Robot Ảo thêm khóa mới chỉ bằng tiếng Việt.
  i18n.appendVi = function(msgs) {
    Object.assign(SRA_VI, msgs);
    applyVi(Object.keys(msgs));
  };
})();
